/* Strings built by script — the pager status, the count line, the combobox —
 * are created AFTER the language swap has walked the DOM, so a [data-i18n]
 * attribute can never reach them. They resolve through this helper instead.
 *
 * A missing key returns the key itself, loudly. §9.6 forbids English
 * fallthrough: a visible gap is honest, a Bulgarian word leaking into an
 * English page is not.
 */
window.AIRBG_LANG = function () {
  return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'bg';
};

window.AIRBG_T = function (key, vars) {
  var dict = window.AIRBG_I18N[window.AIRBG_LANG()] || {};
  var s = dict[key];
  if (s === undefined) return key;
  return s.replace(/\{(\w+)\}/g, function (m, name) {
    return vars && vars[name] !== undefined ? vars[name] : m;
  });
};

/* An oblast's Bulgarian name is its IDENTITY, not its label. It stays on
 * data-name as a stable key; this resolves the label to show. */
window.AIRBG_NAME = function (bgName) {
  if (window.AIRBG_LANG() !== 'en') return bgName;
  return window.AIRBG_OBLAST_EN[bgName] || bgName;
};
